#!/usr/bin/env bash
# Generate the Homebrew tap files for a release from the checksums of the assets
# that release ships, so their version, urls and shasums cannot drift from what
# a person downloads:
#
#   dist/homebrew/Formula/wd.rb             wd, the command-line tool
#   dist/homebrew/Casks/work-director.rb    the macOS app, with its wd on PATH
#
#   VERSION=v1.2.0 scripts/formula.sh       # reads dist/*.sha256
#
# The layout is the tap's own (mkhanal/homebrew-work-director), so publishing is
# copying dist/homebrew over a checkout of it; scripts/tap.sh does that from a
# published release. The release also carries both files as assets.
#
# The formula installs the compiled binary and declares no build dependency: a
# binary formula that names Go would make everyone install a toolchain they
# never use.
set -euo pipefail
cd "$(dirname "$0")/.."

tag=${VERSION:-}
[ -n "$tag" ] || { echo "formula: set VERSION to the tag being released" >&2; exit 1; }
case "$tag" in v*) ;; *) echo "formula: VERSION $tag does not start with v" >&2; exit 1 ;; esac
version=${tag#v}
repo=${REPO:-mkhanal/work-director}
download="https://github.com/${repo}/releases/download/${tag}"

# The sha256 a release asset's .sha256 file records ("<hash>  <file>").
hash_of() {
  local f="dist/$1.sha256"
  [ -f "$f" ] || { echo "formula: missing $f; build the release assets first" >&2; exit 1; }
  awk '{print $1}' "$f"
}

out=dist/homebrew
mkdir -p "$out/Formula" "$out/Casks"

cat > "$out/Formula/wd.rb" <<RUBY
# Generated by scripts/formula.sh for ${tag}. Do not hand-edit: the next release
# overwrites this file.
class Wd < Formula
  desc "Head-of-engineering agent that directs coding agents across many repos"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${download}/wd-darwin-arm64.tar.gz"
      sha256 "$(hash_of wd-darwin-arm64.tar.gz)"
    end
    on_intel do
      url "${download}/wd-darwin-amd64.tar.gz"
      sha256 "$(hash_of wd-darwin-amd64.tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "${download}/wd-linux-arm64.tar.gz"
      sha256 "$(hash_of wd-linux-arm64.tar.gz)"
    end
    on_intel do
      url "${download}/wd-linux-amd64.tar.gz"
      sha256 "$(hash_of wd-linux-amd64.tar.gz)"
    end
  end

  def install
    bin.install "wd"
    man1.install "wd.1"
  end

  def caveats
    <<~EOS
      wd keeps its ledger in ~/.work-director. Next:
        wd doctor     # which coding-agent CLIs it found; one is enough
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/wd --version")
  end
end
RUBY

dmg="Work-Director-${tag}-macos-arm64.dmg"
cat > "$out/Casks/work-director.rb" <<RUBY
# Generated by scripts/formula.sh for ${tag}. Do not hand-edit: the next release
# overwrites this file.
cask "work-director" do
  version "${version}"
  sha256 "$(hash_of "$dmg")"

  url "https://github.com/${repo}/releases/download/v#{version}/Work-Director-v#{version}-macos-arm64.dmg"
  name "Work Director"
  desc "Head-of-engineering agent that directs coding agents across many repos"
  homepage "https://github.com/${repo}"

  depends_on arch: :arm64
  depends_on macos: ">= :sequoia"

  app "Work Director.app"
  binary "#{appdir}/Work Director.app/Contents/MacOS/wd"

  zap trash: "~/.work-director"

  caveats <<~EOS
    Work Director is not notarized yet, so macOS blocks its first open. Open it
    once, then choose Open Anyway in System Settings > Privacy & Security, or run:
      xattr -dr com.apple.quarantine "#{appdir}/Work Director.app"
  EOS
end
RUBY

echo "wrote $out/Formula/wd.rb and $out/Casks/work-director.rb for $tag"
